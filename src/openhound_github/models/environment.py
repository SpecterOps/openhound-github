@dataclass
class GHEnvironmentProperties(GHNodeProperties):
    """Environment-specific properties and accordion panel queries.

    Attributes:
        collected: Collected/generated by OpenHound
        short_name: The environment's display name (e.g., `production`, `staging`).
        can_admins_bypass: Whether repository administrators can bypass environment protection rules.
        repository_name: The full name of the containing repository.
        repository_id: The ID of the containing repository.
        environment_name: The name of the environment (GitHub organization).
    """

    collected: bool = True
    short_name: str | None = None
    can_admins_bypass: bool | None = None
    wait_timer: int | None = None
    required_reviewers: bool = False
    reviewer_count: int = 0
    prevent_self_review: bool | None = None
    protected_branches: bool | None = None
    custom_branch_policies: bool | None = None
    repository_name: str | None = None
    repository_id: str | None = None
    environment_name: str | None = None


